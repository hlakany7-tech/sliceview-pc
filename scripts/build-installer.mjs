// Compiles the Windows installers from dist/win-unpacked with NSIS (makensis, any OS; no Wine needed):
//   dist/Sliceview-Setup-<version>-x64.exe           per user, no administrator rights
//   dist/Sliceview-Setup-AllUsers-<version>-x64.exe  all users, Program Files, needs administrator rights
// Run after `electron-builder --win dir`. Needs makensis 3.x on PATH (Windows: winget install NSIS.NSIS;
// Ubuntu: apt install nsis; macOS: brew install makensis), or MAKENSIS=path.
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const version = pkg.version;
const src = path.join(root, 'dist', 'win-unpacked');
if (!fs.existsSync(path.join(src, 'Sliceview.exe'))) { console.error('dist/win-unpacked/Sliceview.exe not found: run electron-builder --win dir first'); process.exit(1); }

// The uninstaller removes exactly the files that were installed.
const lines = [];
for (const e of fs.readdirSync(src, { withFileTypes: true })) {
  if (e.isDirectory()) lines.push(`RMDir /r "$INSTDIR\\${e.name}"`);
  else lines.push(`Delete "$INSTDIR\\${e.name}"`);
}
const filesNsh = path.join(root, 'dist', 'installer-files.nsh');
fs.writeFileSync(filesNsh, '; generated by scripts/build-installer.mjs\n' + lines.join('\n') + '\n');

const makensis = process.env.MAKENSIS || 'makensis';
const targets = [
  { out: `Sliceview-Setup-${version}-x64.exe`, defs: {} },
  { out: `Sliceview-Setup-AllUsers-${version}-x64.exe`, defs: { ALLUSERS: '1' } },
];
// Both installers are compressed at the same time (LZMA in makensis uses one core each).
const build = t => new Promise((resolve, reject) => {
  const defs = {
    VERSION: version, SRC_DIR: src, OUT_FILE: path.join(root, 'dist', t.out), FILES_NSH: filesNsh,
    ICON: path.join(root, 'build', 'icon.ico'), WIZARD_BMP: path.join(root, 'build', 'installer', 'wizard.bmp'), ...t.defs,
  };
  const args = ['-V2', '-INPUTCHARSET', 'UTF8', ...Object.entries(defs).map(([k, v]) => `-D${k}=${v}`), path.join(root, 'build', 'installer', 'sliceview.nsi')];
  const t0 = Date.now();
  const p = spawn(makensis, args, { stdio: 'inherit' });
  p.on('error', reject);
  p.on('exit', code => {
    if (code !== 0) return reject(new Error('makensis failed for ' + t.out + ' (exit ' + code + ')'));
    const mb = (fs.statSync(path.join(root, 'dist', t.out)).size / 1048576).toFixed(1);
    console.log(`built dist/${t.out} (${mb} MB) in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
    resolve();
  });
});
const only = process.argv.includes('--per-user-only') ? targets.slice(0, 1) : targets;
try { await Promise.all(only.map(build)); } catch (e) { console.error(e.message); process.exit(1); }
